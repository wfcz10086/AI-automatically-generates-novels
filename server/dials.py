DIAL_KEYS = [d["key"] for d in DIALS]


def defaults() -> Dict[str, int]:
    return {d["key"]: int(d["default"]) for d in DIALS}


def normalize(values: Any) -> Dict[str, int]:
    """把任意来源的取值收进 0-100，缺的用默认值补。"""
    out = defaults()
    if isinstance(values, dict):
        for k in DIAL_KEYS:
            v = values.get(k)
            if v is None:
                continue
            try:
                out[k] = max(0, min(100, int(round(float(v)))))
            except (TypeError, ValueError):
                continue
    return out


def _band(spec: List[Tuple[int, int, str]], v: int) -> str:
    for lo, hi, text in spec:
        if lo <= v < hi or (hi >= 100 and v >= lo):
            return text
    return spec[-1][2]


def brief(values: Any) -> str:
    """注入提示词的旋钮块 —— 文风与剧情两头都给。"""
    v = normalize(values)
    lines = ["【本书旋钮（同时管剧情与文风，越界比不足更糟）】"]
    for d in DIALS:
        n = v[d["key"]]
        lines.append(f"■ {d['label']} {n}/100（{d['hint']}）")
        lines.append(f"  剧情上：{_band(d['plot'], n)}")
        lines.append(f"  文风上：{_band(d['style'], n)}")
    return "\n".join(lines)


def derived(values: Any) -> Dict[str, int]:
    """旋钮驱动的**机制参数** —— 光写进提示词不算数。

    模型读到「写得狂野一点」只会写得更用力，结构照旧；所以狂野度直接决定
    每阶段的挫败配额，爽度直接决定爽点必须出现的间隔。提示词管风味，
    这些数管底线。
    """
    v = normalize(values)
    w, g = v["wild"], v["gratify"]
    # 狂野度 → 每阶段必须有几次主角真失手。0-20 也给 1 次：
    # 一次都不失手的主角，读者不会替他担心。
    setback = 1 if w < 40 else (2 if w < 70 else 3)
    # 爽度 → 每几章必须有一次实打实的回报
    if g >= 80:
        beat = 3
    elif g >= 60:
        beat = 5
    elif g >= 40:
        beat = 7
    else:
        beat = 12
    return {"setback_quota": setback, "pleasure_interval": beat}
