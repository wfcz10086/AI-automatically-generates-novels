"""两个旋钮：爽度与狂野度 —— 同时管文风与剧情。

## 为什么是两个而不是一个

「爽」和「狂野」是**正交**的两件事，混成一个滑块就调不出想要的东西：

    爽高·野低   稳定输出爽点，但不冒险 —— 标准套路爽文，看着舒服，不会心慌
    爽高·野高   爽点猛，且随时可能翻车 —— 疯批流，赢得狠也输得惨
    爽低·野高   黑深残 / 严肃向，敢毁东西，但不给读者糖
    爽低·野低   平淡日常

实测某书读到一百五十章开始跳着看，问题恰恰不是「不够爽」——它每章都有爽点、
对手一个比一个强、代价也明写 —— 而是**主角从头到尾都是对的**，
五个阶段零挫败。那是狂野度为零，不是爽度不够。一个滑块表达不了这个差别。

## 两个旋钮各管什么

爽度  = 回报有多猛、多密：爽点间隔、翻盘幅度、对手体量、打脸的即时性；
        文风上管节奏快慢、句子长短、金句密度。
狂野度 = 敢不敢失控：主角会不会真输、会不会死人、会不会毁掉已经建起来的东西、
        意外事件占比、道德灰度；文风上管场面尺度、情绪极端度、语言的粗粝程度。

## 旋钮不只写进提示词，还要改机制

只把「请写得狂野一点」塞进提示词是没用的 —— 模型会写得更用力，但结构照旧。
所以狂野度同时驱动**挫败配额**（每阶段必须有几次主角真失手），
爽度同时驱动**爽点间隔**（每几章必须有一次实打实的回报）。
提示词负责风味，机制负责底线。
"""
